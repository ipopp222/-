document.addEventListener('input', event => {
  const builderInput = event.target.closest('[data-event-builder]');
  if (builderInput) return updateEventBuilder(builderInput);
  const dailyReflection = event.target.closest('[data-daily-reflection]');
  if (dailyReflection) {
    const day = dailyReflection.dataset.dailyReflection;
    const ready = Boolean(dailyReflection.value.trim());
    state.dailyReflections = { ...(state.dailyReflections || {}), [day]: dailyReflection.value };
    localStorage.setItem('digitalMentorState', JSON.stringify(state));
    dailyReflection.closest('.daily-reflection')?.classList.toggle('complete', ready);
    const status = document.querySelector('[data-reflection-status]');
    if (status) status.textContent = ready ? '✓ Сохранено' : 'Сохраняется автоматически';
    updateMyDayProgress();
    return;
  }
  const note = event.target.closest('[data-task-note]');
  if (!note) return;
  state.taskNotes = { ...(state.taskNotes || {}), [note.dataset.taskNote]: note.value };
  localStorage.setItem('digitalMentorState', JSON.stringify(state));
  const marker = document.querySelector('[data-evidence-note]');
  if (marker) {
    const ready = Boolean(note.value.trim());
    marker.classList.toggle('ready', ready);
    marker.textContent = ready ? '✓' : '1';
  }
});

