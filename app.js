function missionTestResult() {
  const scores = Object.keys(missionProfiles).reduce((result, key) => ({ ...result, [key]: 0 }), {});
  Object.values(state.missionTestAnswers || {}).forEach(profile => { if (profile in scores) scores[profile] += 1; });
  return Object.entries(scores).sort((a, b) => b[1] - a[1]).map(([id, score]) => ({ id, score, ...missionProfiles[id] }));
}

