function xmlEscape(value) {
  return String(value ?? '').replace(/[<>&'\"]/g, char => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;', "'": '&apos;', '"': '&quot;' })[char]);
}

function columnName(index) {
  let name = '';
  for (let value = index + 1; value; value = Math.floor((value - 1) / 26)) name = String.fromCharCode(65 + ((value - 1) % 26)) + name;
  return name;
}

function worksheetXml(rows) {
  const body = rows.map((row, rowIndex) => `<row r="${rowIndex + 1}">${row.map((value, columnIndex) => {
    const ref = `${columnName(columnIndex)}${rowIndex + 1}`;
    return typeof value === 'number' ? `<c r="${ref}"><v>${value}</v></c>` : `<c r="${ref}" t="inlineStr"><is><t xml:space="preserve">${xmlEscape(value)}</t></is></c>`;
  }).join('')}</row>`).join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>${body}</sheetData></worksheet>`;
}

function crc32(bytes) {
  let crc = 0xffffffff;
  for (const byte of bytes) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit += 1) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
  }
  return (crc ^ 0xffffffff) >>> 0;
}

function push16(target, value) { target.push(value & 255, (value >>> 8) & 255); }
function push32(target, value) { target.push(value & 255, (value >>> 8) & 255, (value >>> 16) & 255, (value >>> 24) & 255); }

function createXlsx(sheets) {
  const encoder = new TextEncoder();
  const names = Object.keys(sheets);
  const files = {
    '[Content_Types].xml': `<?xml version="1.0" encoding="UTF-8"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>${names.map((_, index) => `<Override PartName="/xl/worksheets/sheet${index + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>`).join('')}</Types>`,
    '_rels/.rels': '<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>',
    'xl/workbook.xml': `<?xml version="1.0" encoding="UTF-8"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>${names.map((name, index) => `<sheet name="${xmlEscape(name)}" sheetId="${index + 1}" r:id="rId${index + 1}"/>`).join('')}</sheets></workbook>`,
    'xl/_rels/workbook.xml.rels': `<?xml version="1.0" encoding="UTF-8"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">${names.map((_, index) => `<Relationship Id="rId${index + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet${index + 1}.xml"/>`).join('')}</Relationships>`
  };
  names.forEach((name, index) => { files[`xl/worksheets/sheet${index + 1}.xml`] = worksheetXml(sheets[name]); });
  const parts = [];
  const central = [];
  let offset = 0;
  Object.entries(files).forEach(([name, value]) => {
    const fileName = encoder.encode(name);
    const data = encoder.encode(value);
    const checksum = crc32(data);
    const local = [];
    push32(local, 0x04034b50); push16(local, 20); push16(local, 0x0800); push16(local, 0); push16(local, 0); push16(local, 0); push32(local, checksum); push32(local, data.length); push32(local, data.length); push16(local, fileName.length); push16(local, 0);
    parts.push(new Uint8Array(local), fileName, data);
    central.push({ fileName, checksum, size: data.length, offset });
    offset += local.length + fileName.length + data.length;
  });
  const centralStart = offset;
  central.forEach(file => {
    const header = [];
    push32(header, 0x02014b50); push16(header, 20); push16(header, 20); push16(header, 0x0800); push16(header, 0); push16(header, 0); push16(header, 0); push32(header, file.checksum); push32(header, file.size); push32(header, file.size); push16(header, file.fileName.length); push16(header, 0); push16(header, 0); push16(header, 0); push16(header, 0); push32(header, 0); push32(header, file.offset);
    parts.push(new Uint8Array(header), file.fileName);
    offset += header.length + file.fileName.length;
  });
  const end = [];
  push32(end, 0x06054b50); push16(end, 0); push16(end, 0); push16(end, central.length); push16(end, central.length); push32(end, offset - centralStart); push32(end, centralStart); push16(end, 0);
  parts.push(new Uint8Array(end));
  return new Blob(parts, { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' });
}

