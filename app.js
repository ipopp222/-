function loadState() {
  try {
    const loaded = { ...defaultState, ...JSON.parse(localStorage.getItem('digitalMentorState')) };
    if (!loaded.userId) loaded.userId = crypto.randomUUID();
    return loaded;
  } catch { return { ...defaultState, userId: crypto.randomUUID() }; }
}

function saveState() {
  localStorage.setItem('digitalMentorState', JSON.stringify(state));
  recordUser();
  updateProfile();
}

function loadAnalytics() {
  try { return { users: {}, events: [], ...JSON.parse(localStorage.getItem('digitalMentorAnalytics')) }; }
  catch { return { users: {}, events: [] }; }
}

function saveAnalytics() {
  localStorage.setItem('digitalMentorAnalytics', JSON.stringify(analytics));
}

function recordUser() {
  if (!state.onboarded || !state.name) return;
  const previous = analytics.users[state.userId] || {};
  analytics.users[state.userId] = {
    ...previous,
    id: state.userId,
    name: state.name,
    location: state.location || '',
    organization: state.organization || '',
    workplace: state.workplace || '',
    firstSeen: previous.firstSeen || Date.now(),
    lastSeen: Date.now(),
    visits: previous.visits || 0,
    completed: [...state.completed],
    progress: progress(),
    activeWeek: unlockedWeekIndex() + 1,
    lastView: currentView
  };
  saveAnalytics();
}

function trackActivity(type, detail = '') {
  if (!state.onboarded || !state.name) return;
  recordUser();
  analytics.events.push({ userId: state.userId, type, detail, createdAt: Date.now() });
  analytics.events = analytics.events.slice(-2000);
  saveAnalytics();
}

function trackVisit() {
  if (!state.onboarded || !state.name || sessionStorage.getItem('digitalMentorVisitTracked')) return;
  recordUser();
  analytics.users[state.userId].visits += 1;
  analytics.users[state.userId].lastSeen = Date.now();
  analytics.events.push({ userId: state.userId, type: 'visit', detail: 'Открытие сайта', createdAt: Date.now() });
  analytics.events = analytics.events.slice(-2000);
  sessionStorage.setItem('digitalMentorVisitTracked', '1');
  saveAnalytics();
}

function completedCount() { return tasks.filter(task => state.completed.includes(task.id)).length; }
function progress() { return Math.round((completedCount() / tasks.length) * 100); }

function isWeekComplete(index) {
  return taskWeeks[index].tasks.every(task => state.completed.includes(task.id));
}

function unlockedWeekIndex() {
  let index = 0;
  while (index < taskWeeks.length - 1 && isWeekComplete(index)) index += 1;
  return index;
}

function activeWeekRemaining() {
  const week = taskWeeks[unlockedWeekIndex()];
  return week.tasks.filter(task => !state.completed.includes(task.id)).length;
}

