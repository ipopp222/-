function eventUsefulness(draft = {}) {
  const format = draft.customFormat?.trim() || draft.format;
  const score = (draft.audience?.trim().length >= 8 ? 10 : 0)
    + (draft.need?.trim().length >= 15 ? 12 : 0)
    + (format ? 8 : 0)
    + Math.min(2, Number(draft.participation) || 0) * 6
    + (draft.result?.trim().length >= 15 ? 14 : 0)
    + (Number(draft.participants) > 0 ? 6 : 0)
    + (draft.venue?.trim() ? 6 : 0)
    + (draft.date ? 5 : 0)
    + (draft.time ? 5 : 0)
    + (draft.resources?.trim().length >= 10 ? 8 : 0)
    + (draft.accessible ? 4 : 0)
    + (draft.safe ? 4 : 0)
    + (draft.feedback ? 3 : 0)
    + (draft.nextStep ? 3 : 0);
  const missing = [];
  if (!draft.audience?.trim() || draft.audience.trim().length < 8) missing.push('уточните конкретную аудиторию');
  if (!draft.need?.trim() || draft.need.trim().length < 15) missing.push('опишите подтверждённую потребность');
  if (!format) missing.push('выберите или предложите свой формат');
  if (Number(draft.participation) < 2) missing.push('добавьте активное действие участника');
  if (!draft.result?.trim() || draft.result.trim().length < 15) missing.push('сформулируйте наблюдаемый результат');
  if (!(Number(draft.participants) > 0)) missing.push('укажите число участников');
  if (!draft.venue?.trim()) missing.push('укажите место');
  if (!draft.date || !draft.time) missing.push('укажите дату и время');
  if (!draft.resources?.trim() || draft.resources.trim().length < 10) missing.push('перечислите доступные ресурсы');
  if (!draft.accessible) missing.push('проверьте доступность');
  if (!draft.safe) missing.push('предусмотрите безопасность');
  if (!draft.feedback) missing.push('добавьте обратную связь');
  if (!draft.nextStep) missing.push('определите следующий шаг');
  const label = score >= 80 ? 'Сильная концепция' : score >= 55 ? 'Полезная основа' : 'Нужно усилить пользу';
  return { score, label, missing };
}

